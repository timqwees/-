<p>Компрессоры — это устройства, которые сжимают воздух для питания инструментов, очистки и пневмоустройств. Как выбрать компрессор для строительства: тип, мощность и расход воздуха.</p>

<h2>Типы компрессоров</h2>
<div data-type="list">
<ol>
<li><strong>Поршневые компрессоры</strong> — классические, надёжные, доступные. Работают на бензине или электричестве.</li>
<li><strong>Винтовые компрессоры</strong> — более компактные, постоянного действия. Тихие, для профессионального применения.</li>
<li><strong>Центробежные (торцевые)</strong> — для больших расходов, промышленного применения.</li>
</ol>
</div>

<h2>Как рассчитать расход воздуха</h2>
<p>Суммируйте расход всех инструментов, которые будут работать одновременно. Добавьте 20% запас.</p>

