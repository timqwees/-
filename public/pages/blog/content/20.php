<p>Гарантии на строительство БВЗ — важный элемент договора. Заказчик должен знать, на что опираться, и какие гарантии действительно важны для защиты своих интересов.</p>

<h2>Типы гарантий на БВЗ</h2>
<div data-type="list">
<ol>
<li><strong>Гарантия на каркас</strong> — 10 лет на металлоконструкции, 5 лет на покрытие.</li>
<li><strong>Гарантия на кровлю</strong> — 10 лет на металочерепицу, 15 лет на ПВХ покрытие.</li>
<li><strong>Гарантия на теплоизоляцию</strong> — 5 лет на сэндвич-панели, 3 года на минеральную вату.</li>
<li><strong>Гарантия на фундамент</strong> — 3 года на сваи и плиты, 5 лет на монолит.</li>
<li><strong>Гарантия на ИЖС</strong> — 2 года на электромонтаж, 3 года на водопровод.</li>
</ol>
</div>

