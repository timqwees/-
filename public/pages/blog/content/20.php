<div data-type="box" data-color="blue">
<h3>💡 Важно!</h3>
<p>Гарантия не действует, если: несоблюдены условия эксплуатации, самовольные перестройки, стихийные бедствия без страховки.</p>
</div>

<h2>Что должно быть в договоре</h2>
<ol>
<li>Полное описание объекта (площадь, планировка, материалы)</li>
<li>Смета с разбивкой по статьям и этапам оплаты</li>
<li>Сроки выполнения работ и сдачи объекта</li>
<li>Гарантийный срок и объём ответственности подрядчика</li>
<li>Штрафные санкции за просрочку</li>
<li>Порядок и сроки устранения брака</li>
</ol>

<h2>Как проверить качество БВЗ</h2>
<ul>
<li>Толщина стали (по марки — не менее 0,45 мм для каркаса)</li>
<li>Параллельность стен (отклонение не более 3 мм на 1 м)</li>
<li>Герметичность (нет протечек на стыках)</li>
<li>Вентиляция в закрытом объёме (отсутствие конденсата)</li>
</ul>

<p>ФАВОРИТ-СТРОЙ-СНАБ: гарантия 5 лет на все конструкции БВЗ и 3 года на инженерные сети. Прозрачный договор без скрытых платежей.</p>
