<li>Смесители и сантех. элементы</li>
<li>Канализационная колонка с углом</li>
</ul>

<h2>Отопление БВЗ</h2>
<p>Варианты отопления:</p>
<ol>
<li><strong>Электроконвекторы</strong> — просты, но дорого в эксплуатации</li>
<li><strong>Инфракрасные панели</strong> — экономичны, мгновенно согревают</li>
<li><strong>Тёплый пол</strong> — комфортно, но сложнее в установке</li>
<li><strong>Водяное отопление</strong> — через ДГУ или котел</li>
</ol>

<h2>Вентиляция</h2>
<p>Обязательна для любого закрытого БВЗ:</p>
<ul>
<li>Приточная вентиляция (вентиляторы на вход)</li>
<li>Вытяжная вентиляция (вытяжки на выход)</li>
<li>Расчёт приточного воздуха: 30 м³/ч на одного человека</li>
</ul>

