<p>Ошибки при строительстве БВЗ — самая дорогая статья. Исправить брак после сдачи объекта в 5–10 раз дороже, чем избежать его изначально. Вот 5 ошибок, которые гарантированно наложатся на ваш бюджет.</p>

<h2>Ошибка #1: Экономия на проекте</h2>
<p><strong>Проблема:</strong> Многие заказчики экономят на проекте, полагая «всё можно без чертежей».</p>
<p><strong>Последствия:</strong> Переплата за переделки, невозможность согласовать с инженерными сетями, риск краха конструкции.</p>
<p><strong>Решение:</strong> Доверяйте проекту — это 3–5% от бюджета, но экономия 15–20% на исполнстве гарантирована.</p>

<h2>Ошибка #2: Неверный выбор фундамента</h2>
<p><strong>Проблема:</strong> Ставят плиту на глине без свай — через год фундамент проседает.</p>
<p><strong>Последствия:</strong> Смещение стен, заедание дверей, разрушение оконных проёмов.</p>
<p><strong>Решение:</strong> Геология + расчёт фундамента обязательны. Мы делаем это всегда.</p>

<h2>Ошибка #3: Нет защиты от осадков</h2>
<p><strong>Проблема:</strong> Картер без уклона, вода стоит у основания.</p>
<p><strong>Последствия:</strong> Гниение фундамента, протечки в стенах, плесень.</p>
<p><strong>Решение:</strong> Уклон 2–3% к системе отведения воды + гидроизоляция.</p>

