<p>Капитальный ремонт школы — это сложный многокомпонентный проект, требующий тщательного планирования. Мы расскажем о каждом этапе.</p>

<h2>Этапы капитального ремонта школы</h2>
<div data-type="list">
<ol>
<li><strong>Дефектная ведомость (10–15 дней)</strong> — выявление всех повреждений и необходимых работ.</li>
<li><strong>Проект ремонта (15–20 дней)</strong> — чертежи, смета, согласования.</li>
<li><strong>Раздельные демонтажные работы (10–15 дней)</strong> — безопасное снятие старых покрытий.</li>
<li><strong>Фундаментные работы (20–30 дней)</strong> — устройство или ремонт фундаментов.</li>
<li><strong>Монтаж несущих конструкций (15–20 дней)</strong> — каркас, перекрытия, чердацкие плиты.</li>
<li><strong>Кровля и фасады (25–30 дней)</strong> — герметизация, утепление, отделка фасадов.</li>
<li><strong>Внутренние стены и потолки (20–25 дней)</strong> — штукровка, гипсокартон, покраска.</li>
<li><strong>Инженерные сети (30–40 дней)</strong> — электрика, вода, канализация, отопление, вентиляция.</li>
<li><strong>Чистовая отделка (20–25 дней)</strong> — напольные покрытия, мебель, мелкий ремонт.</li>
<li><strong>Приёмка и ввод в эксплуатацию (5–10 дней)</strong> — акт приёмки, ввод ЗОЖ в эксплуатацию.</li>
</ol>
</div>

