<h2>Технические решения</h2>
<ul>
	<li><strong>Модули:</strong> 3×7 м, рама из двутавров 160/200, стойки 80×80×4, перекрытия — профлист Н75 + цементно-стружечная плита 18 мм.</li>
	<li><strong>Утепление:</strong> ППУ 100 мм (стены), 150 мм (перекрытия), минвата 150 мм (перегородки, звукоизоляция).</li>
	<li><strong>Фундамент:</strong> Ленточный неглубокий (закладка 0.5 м), бетон М350 В25, арматура А500С, УШП не применялся — грунт песок средней крупности.</li>
	<li><strong>ИЖС:</strong> Ввод 150 кВт (ТП 250 кВА), водоснабжение — 2 ввода (п/в, х/в), отопление — водяное (котлов 2×150 кВт + конвекторы), вентиляция — приточные установки с рекуперацией 70%.</li>
	<li><strong>Пожарная безопасность:</strong> ППС tipo 3, светотехника эвакуации, стойки ПЖ, обработка древесины Огнебио.</li>
</ul>

<h2>Логистика: транзит 1500 км</h2>
<p>Маршрут: Завод ФСС (Москва) → М-4 «Дон» → Сочи, Адлерский р-н. 5 рейсов по 24 модуля (фуры 13.6 м, высота 2.9 м). Перевозка только ночью (22:00–06:00) по требованию ГИБДД на М-4 в сезон. Подача на площадку — через временную дорогу (ПГС 300 мм), автокран 50 т на гусеничном ходу. Монтажный цикл 1 корпуса: 3 дня — установка 30 модулей, 2 дня — стыковка и кровля, 2 дня — внутренние перегородки.</p>

