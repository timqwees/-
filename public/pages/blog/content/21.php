<h2>Разбор по типам объектов</h2>

<h3>Ангары: холодные vs тёплые vs морозильные</h3>
<p>Ключевой фактор — толщина и тип сэндвич-панели. Холодный ангар (профлист/одинарная панель 50 мм) стоит <strong>25–30 тыс. ₽/м²</strong>. Тёплый (ППУ 100–150 мм или минералка 150–200 мм) — <strong>31–40 тыс. ₽/м²</strong>. Морозильная камера (ППУ 150–200 мм + паробарьер + теплорывки) — <strong>45–55 тыс. ₽/м²</strong>.</p>
<p>Дополнительно: кран-балка 3.2 т — +150 тыс. ₽, 5 т — +280 тыс., 10 т — +550 тыс. Высота выше 6 м — каждый метр +5–7% к цене м².</p>

<h3>Склады: классы D, B+, A</h3>
<p>Класс D (холодный, без отопления, бетонный пол) — <strong>28–35 тыс. ₽/м²</strong>. Класс B+ (тёплый, доковые ворота, эпоксидный пол, вентиляция) — <strong>35–42 тыс. ₽/м²</strong>. Класс A (полная автоматизация, полиуретановый пол, спринклеры) — <strong>45–48 тыс. ₽/м²</strong>. Доковое ворото — +180 тыс. ₽/шт.</p>

<h3>Модульные АБК и общежития</h3>
<p>Модуль 3×7 м (коробка) — 380–420 тыс. ₽. Под ключ (ИЖС, отделка, мебель) — <strong>42–65 тыс. ₽/м²</strong> для АБК и <strong>45–62 тыс. ₽/м²</strong> для общежитий. Этажность: 1 этаж — база, 2 этажа — ×1.14, 3 этажа — ×1.31. Назначение: офис — база, общежитие — ×1.07, медпункт — ×1.38, школа — ×1.48.</p>

