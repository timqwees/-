<h2>Типы навесов</h2>
<div data-type="list">
<ol>
<li><strong>Арочные навесы</strong> — классическая форма, подходит для входов и террас.</li>
<li><strong>Каркасные навесы</strong> — металлокаркас + профнастил/сэндвич. Универсальны для любого объекта.</li>
<li><strong>Навесы из бетонных плит</strong> — прочные, долговечные, но дорогие.</li>
<li><strong>Навесы из поликарбоната</strong> — лёгкие, пропускают свет, хороши для детских площщадок.</li>
</ol>
</div>

