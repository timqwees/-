<p>Теплоизоляция для БВЗ выбирается по трём параметрам: теплопроводности, паропроницаемости и стоимости. Сравниваем самые популярные варианты.</p>

<h2>Минеральная вата (каменная и стекловата)</h2>
<p><strong>Плюсы:</strong> паропроницаемая, пожарная стойкость, хорошая звукоизоляция.</p>
<p><strong>Минусы:</strong> требует защиты от влаги при монтаже, чуть дороже.</p>
<p><strong>Теплопроводность:</strong> 0,034–0,040 Вт/(м·°C)</p>
<p><strong>Цена:</strong> 600–900 ₽/м² за слой 100 мм</p>

<h2>Пенополистирол (ППС)</h2>
<p><strong>Плюсы:</strong> низкая стоимость, прост в монтаже, не впитывает влагу.</p>
<p><strong>Минусы:</strong> не паропроницаем, горюч, плохая звукоизоляция.</p>
<p><strong>Теплопроводность:</strong> 0,028–0,034 Вт/(м·°C)</p>
<p><strong>Цена:</strong> 400–700 ₽/м² за слой 100 мм</p>

<h2>Пенополиуретан (ППУ)</h2>
<p><strong>Плюсы:</strong> самая низкая теплопроводность, герметичный слой.</p>
<p><strong>Минусы:</strong> требует защиты от ультрафиолета, дорогой.</p>
<p><strong>Теплопроводность:</strong> 0,022–0,026 Вт/(м·°C)</p>
<p><strong>Цена:</strong> 1 200–1 800 ₽/м² за слой 100 мм</p>

